  function t(lang, key, vars) {
    const table = STRINGS[lang] || STRINGS.he;
    let s = table[key];
    if (s == null) s = STRINGS.en[key] != null ? STRINGS.en[key] : key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
    return s;
  }

  function locale(lang) {
    // en-GB gives 24h clock and day/month order, which matches how Israeli users read dates.
    return lang === 'en' ? 'en-GB' : 'he-IL';
  }

  function dir(lang) {
    return lang === 'he' ? 'rtl' : 'ltr';
  }

  return { STRINGS, t, locale, dir };
